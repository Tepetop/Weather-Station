/**
 * @brief Convert between CP850 OEM and Unicode.
 * @param chr Character to convert.
 * @param dir 0: Unicode to OEM, 1: OEM to Unicode.
 * @retval Converted character, or 0 if unmapped.
 */
WCHAR ff_convert(WCHAR chr, UINT dir) {
  UINT i;

  if (chr < 0x80U) {
    return chr;
  }

  if (dir != 0U) {
    return (chr >= 0x100U) ? (WCHAR)0 : sd_cp850_tbl[chr - 0x80U];
  }

  for (i = 0U; i < 128U; i++) {
    if (chr == sd_cp850_tbl[i]) {
      return (WCHAR)(i + 0x80U);
    }
  }

  return 0;
}

/**
 * @brief Convert a Unicode character to uppercase (ASCII + Latin-1).
 * @param chr Unicode character.
 * @retval Uppercase character, or @p chr if unchanged.
 */
WCHAR ff_wtoupper(WCHAR chr) {
  if ((chr >= 0x61U) && (chr <= 0x7AU)) {
    return (WCHAR)(chr - 0x20U);
  }
  if ((chr >= 0xE0U) && (chr <= 0xFEU) && (chr != 0xF7U)) {
    return (WCHAR)(chr - 0x20U);
  }
  return chr;
}

